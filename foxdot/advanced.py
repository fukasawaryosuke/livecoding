# --- 1. 複雑なパターン生成 ---

# 複数のパターンを混ぜる（additive chaining）
p1 >> pluck(P[0, 2, 4, 7] | P[7, 5, 3, 0], dur=1/2)

# 連続するノートをスライスして繰り返し
p2 >> bass(P[0:4].loop(), dur=1)

# ランダムに音を変える
p3 >> lead(PRand([0, 2, 4, 5, 7]), dur=0.25)

# 音高を変化させるTimeVarを使った例（一定ビートごとに変わる値）
root = var([0, 2, 4, 5], 8)
p4 >> pluck(root + P[0, 2, 4, 7], dur=1/2)

# --- 2. 時間変数 TimeVar の使い方 ---

# 4拍ごとにベースのトーンを変える
bass_note = var([0, -2, 3, 5], 4)
b1 >> bass(bass_note)

# 16拍かけてAMPを上げるフェードイン効果
fade_in = linvar([0, 1], 16)
p1 >> pluck([0, 2, 4], amp=fade_in)

# --- 3. プレイヤーの制御・同期 ---

# 他のプレイヤーのパターンをフォローしつつ音の高さを変える
p2 >> pluck(dur=1/2).follow(p1) + [0, 2, 4]

# プレイヤーの再生速度を変える（倍速・スローモーション）
p1 >> pluck([0, 2, 4, 7], dur=0.25)  # 通常速
p1 >> pluck([0, 2, 4, 7], dur=1)     # 遅く再生

# プレイヤーにエフェクトをかける例
p1 >> pluck([0, 2, 4, 5], echo=0.5, delay=0.25)

# --- 4. サンプル再生（ドラムや効果音） ---

# 簡単なドラムパターン
d1 >> play("x-o-")

# ドラムの音を別のサンプルに差し替え、パンを左右に振る
d2 >> play("  *  o ", sample=2, pan=(-1,1))

# サンプル音量を上げ下げする
d1 >> play("x-o-", amp=0.8)

# --- 5. エフェクトの追加例 ---

# リバーブを加えたり
p1 >> pluck([0, 2, 4], room=0.7, verb=0.5)

# ローパスフィルターでカットオフ低めに設定
p1 >> pluck([0, 2, 4], cutoff=4000)

# 音の広がりを操作（spread）
d1 >> play("x-o-", spread=0.7)

# --- 6. カスタム関数の作成 ---

# 自分でプレイヤーの度数を上げる関数を作る例
@player_method
def up_octave(self):
    self.degree = self.degree + 12  # 12で1オクターブ上げる
    return self

# 使い方
p1 >> pluck([0, 2, 4]).up_octave()

# --- 7. 変数・パターンの高度活用 ---

# ループしながら外部変数を使って変化させる
beat_val = var([0, 4, 7, 11], 8)
p2 >> bass(beat_val + P[0, -2, -4, -5], dur=1)

# 複数のパターンを掛け合わせる
p3 >> pluck(P[0, 1, 2] * P[0, 2], dur=1/4)

